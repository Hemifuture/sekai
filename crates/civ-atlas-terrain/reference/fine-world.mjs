// Original fixed-source world and windows: seed42/default, first mouth/lake and fixed wrap.
// Run once with tsx; large diagnostic arrays stay outside the production crate.
import {writeFileSync} from 'node:fs';
import {resolve,join} from 'node:path';
import {pathToFileURL} from 'node:url';
import {execFileSync} from 'node:child_process';
import {verifyOriginalModuleProvenance} from './source-pins.mjs';
const [root,prefix,out]=process.argv.slice(2).map(p=>resolve(p));
const provenance=verifyOriginalModuleProvenance(root,prefix);
const imp=name=>import(pathToFileURL(join(root,'src/gen',name+'.ts')));
const {generateWorld,DEFAULT_PARAMS}=await imp('world');
const {rasterize}=await imp('raster');const {zoomSource,rasterizeWindow,WINDOW_PAD}=await imp('rasterWindow');const {mouthsOf}=await imp('estuary');
const {creeksOf}=await imp('creeks');const {seaIceNodes}=await imp('seaice');
const world=generateWorld({...DEFAULT_PARAMS,seed:42});
const whole=rasterize(world,1,false);const source=zoomSource(world,whole);
for(const [key,a]of Object.entries({base:source.base,whole_elevation:whole.elev,whole_water:whole.water,ice_nodes:seaIceNodes(world)}))writeFileSync(join(prefix,`fine-${key}.bin`),new Uint8Array(a.buffer,a.byteOffset,a.byteLength));
writeFileSync(join(prefix,'fine-mouths.json'),JSON.stringify(source.mouths));
const creeks=creeksOf(world);writeFileSync(join(prefix,'fine-creeks.json'),JSON.stringify(creeks.map(r=>({pts:Array.from(r.pts),cells:Array.from(r.cells)}))));
const b=new DataView(new ArrayBuffer(4));const bits=x=>{b.setFloat32(0,x);return b.getUint32(0)};
const lines=['// Generated by fine-world.mjs; fixed default seed42. Not a production world snapshot.',...provenance.map(s=>'// '+s)];
const hash=a=>Array.from(a).reduce((h,v)=>BigInt.asUintN(64,(h^BigInt(v))*1099511628211n),14695981039346656037n).toString();
for(const [key,a]of Object.entries({BASE:source.base,WHOLE_ELEVATION:whole.elev,ICE_NODES:seaIceNodes(world)}))lines.push(`pub(crate) const ${key}_HASH: u64 = ${hash(Array.from(a,bits))};`);
lines.push(`pub(crate) const WHOLE_WATER_HASH: u64 = ${hash(whole.water)};`);
lines.push(`pub(crate) const MOUTH_COUNT: usize = ${source.mouths.length};`,`pub(crate) const CREEK_COUNT: usize = ${creeks.length};`);
const lake=world.water.findIndex(w=>w===2);
const centers=[[source.mouths[0].cx,source.mouths[0].cy],[world.mesh.x[lake],world.mesh.y[lake]],[0,world.height/2]];
lines.push('pub(crate) const WINDOW: &[(u8,f64,f64,u32,u8)] = &[');
for(const [cx,cy] of centers) for(const scale of [2,4,8]) {
 const x0=Math.round((cx-16)*scale)-WINDOW_PAD,y0=Math.round((cy-16)*scale)-WINDOW_PAD,extent=32*scale;
 const r=rasterizeWindow(source,scale,x0,y0,extent+2*WINDOW_PAD,extent+2*WINDOW_PAD);
 for(let y=WINDOW_PAD;y<r.h-WINDOW_PAD;y++)for(let x=WINDOW_PAD;x<r.w-WINDOW_PAD;x++)if(x%scale===0&&y%scale===0){const k=y*r.w+x;lines.push(`(${scale},${(x0+x+.5)/scale},${(y0+y+.5)/scale},${bits(r.elev[k])},${r.water[k]}),`);}
}
// The highest accepted source scale needs only its next-octave pixel boundary;
// broad scale sensitivity remains the three existing S2/4/8 windows above.
{
 const S=16,x0=Math.round(centers[0][0]*S)-8,y0=Math.round(centers[0][1]*S)-8;
 const r=rasterizeWindow(source,S,x0,y0,17,17);
 for(const y of [4,8,12])for(const x of [4,8,12]){const k=y*r.w+x;lines.push(`(${S},${(x0+x+.5)/S},${(y0+y+.5)/S},${bits(r.elev[k])},${r.water[k]}),`);}
}
lines.push('];');
// Default world has no deltas. One controlled historical-flow input exercises the
// original DELTA_F and >500 distributary branches without searching seeds or maps.
const controlled=source.lines.map(d=>({...d,f:d.f.map(()=>1000)}));
const controlledMouths=mouthsOf(world,controlled,whole,source.base,source.bw,source.bh);
const delta=controlledMouths.find(m=>m.delta);const bridge=source.mouths.find(m=>m.bridge);
if(!delta||!bridge)throw Error('required branch fixture missing');
lines.push('pub(crate) const ESTUARY_BRANCH: &[(bool,f64,f64,u32,u8)] = &[');
for(const [isDelta,mouth,src]of [[false,bridge,source],[true,delta,{...source,mouths:controlledMouths}]]) {
 const scale=4,extent=32*scale,x0=Math.round((mouth.cx-16)*scale)-WINDOW_PAD,y0=Math.round((mouth.cy-16)*scale)-WINDOW_PAD;
 const r=rasterizeWindow(src,scale,x0,y0,extent+2*WINDOW_PAD,extent+2*WINDOW_PAD);
 for(let y=WINDOW_PAD;y<r.h-WINDOW_PAD;y+=scale)for(let x=WINDOW_PAD;x<r.w-WINDOW_PAD;x+=scale){const k=y*r.w+x;lines.push(`(${isDelta},${(x0+x+.5)/scale},${(y0+y+.5)/scale},${bits(r.elev[k])},${r.water[k]}),`);}
}
lines.push('];');writeFileSync(out,lines.join('\n'));execFileSync('rustfmt',['--edition','2021',out]);
console.log(JSON.stringify({cells:world.mesh.n,mouths:source.mouths.length,creeks:creeks.length,lake}));
