// Execute original pinned TypeScript with tsx; no replacement terrain algorithm.
import {readFileSync,writeFileSync} from 'node:fs';
import {resolve,join} from 'node:path';
import {pathToFileURL} from 'node:url';
import {execFileSync} from 'node:child_process';
import {SOURCE_PINS,DEPENDENCY_PINS,verifyPin} from './source-pins.mjs';
const [root,prefix,out]=process.argv.slice(2).map(p=>resolve(p));
const provenance=[];
for(const file of Object.keys(DEPENDENCY_PINS))provenance.push(verifyPin(DEPENDENCY_PINS,file,readFileSync(join(prefix,'node_modules',file))));
for(const file of Object.keys(SOURCE_PINS))provenance.push(verifyPin(SOURCE_PINS,file,readFileSync(join(root,'src/gen',file))));
const imp=name=>import(pathToFileURL(join(root,'src/gen',name+'.ts')));
const {Gullies}=await imp('gully');
const {riverGeometry}=await imp('riverGeometry');
const {carveValleys}=await imp('valleys');
const b=new DataView(new ArrayBuffer(8));
const bits=x=>{b.setFloat64(0,x);return b.getBigUint64(0).toString()};
const fb=x=>{b.setFloat32(0,x);return b.getUint32(0)};
const lines=['// Generated by fine.mjs from original pinned source; do not edit.',...provenance.map(s=>'// '+s)];
const inputs=[[123.4,-23.1,45.6,0,1,1,0,0,10,20,100],[-16,-0.01,1,1,0,0,1,0,-20,0.5,71]];
lines.push('pub(crate) const GULLY: &[([f64;11],f64,u64)] = &[');
for(const a of inputs)for(const scale of [2,4,8,16])lines.push(`([${a.map(v=>Number.isInteger(v)?v+'.0':v)}],${scale}.0,${bits(new Gullies(42).height(...a,scale))}),`);
lines.push('];');
// Joining chains, seam crossing and lake origin in one bounded geometric fixture.
const rivers=[{pts:new Float32Array([2046,20,30,2047,22,60,1,25,110,3,27,180])},{pts:new Float32Array([5,20,22,3,23,31,1,25,110])},{pts:new Float32Array([2042,16,30,2043,18,30,2046,20,30])}];
const dense=riverGeometry(rivers,25,{minW:.5,maxW:7.5,fluxRef:1400},1.5,.65,2048);
lines.push('type DenseFixture = (&\'static [u64],&\'static [u64],&\'static [u64],&\'static [u64],Option<usize>);','pub(crate) const DENSE: &[DenseFixture] = &[');
for(const d of dense)lines.push(`(&[${d.x.map(bits)}],&[${d.y.map(bits)}],&[${d.w.map(bits)}],&[${d.f.map(bits)}],${d.mouth===undefined?'None':`Some(${d.mouth})`}),`);
lines.push('];');
for(const scale of [2,4]){const carve=new Float32Array(16*16),calm=new Float32Array(16*16);carveValleys(dense,25,scale,16,16,carve,calm,-4*scale,20*scale,2048*scale);lines.push(`pub(crate) const CARVE_${scale}: &[u32] = &[${Array.from(carve,fb)}];`,`pub(crate) const CALM_${scale}: &[u32] = &[${Array.from(calm,fb)}];`);}
writeFileSync(out,lines.join('\n'));execFileSync('rustfmt',['--edition','2021',out]);
