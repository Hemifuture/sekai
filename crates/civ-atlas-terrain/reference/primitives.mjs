// Offline oracle: execute the pinned TypeScript, not a second JS implementation.
// node primitives.mjs <upstream-checkout> <oracle-prefix> <output-primitives.rs>
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { stripTypeScriptTypes } from 'node:module';
import { execFileSync } from 'node:child_process';
import { SOURCE_PINS, verifyPin, verifyDependencyProvenance } from './source-pins.mjs';

const [upstream, prefix, output] = process.argv.slice(2).map(p => resolve(p));
const temp = join(prefix, 'primitive-modules');
await mkdir(temp, { recursive: true });
const sourceHashes = [];
for (const [name, relative] of [['util', 'util.ts'], ['noise', 'noise.ts'], ['rand', 'civ/engine/rand.ts']]) {
  const source = await readFile(join(upstream, 'src/gen', relative), 'utf8');
  sourceHashes.push(verifyPin(SOURCE_PINS, relative, source));
  const js = stripTypeScriptTypes(source).replaceAll("'./util'", "'./util.mjs'").replaceAll("'../../util'", "'./util.mjs'");
  await writeFile(join(temp, `${name}.mjs`), js);
}
const hashes = [...verifyDependencyProvenance(prefix, join(temp, 'noise.mjs')), ...sourceHashes];
const { mulberry32, subSeed, keyed } = await import(pathToFileURL(join(temp, 'util.mjs')));
const { noise3, fbm3, ridged3, tileableFbm } = await import(pathToFileURL(join(temp, 'noise.mjs')));
const { round24 } = await import(pathToFileURL(join(temp, 'rand.mjs')));
const buf = new DataView(new ArrayBuffer(8));
const bits = x => { buf.setFloat64(0, x); return buf.getBigUint64(0).toString(); };
const f32bits = x => { buf.setFloat32(0, x); return buf.getUint32(0).toString(); };
const float = x => Number.isInteger(x) ? `${x}.0` : `${x}`;
const lines = ['// Generated by primitives.mjs from the pinned upstream; do not edit.', ...hashes.map(x => `// ${x}`)];
lines.push('const STREAMS: &[(u32, &[u64])] = &[');
for (const seed of [0, 42, 4294967295]) {
  const rng = mulberry32(seed);
  lines.push(`(${seed}, &[${Array.from({length: 8}, () => bits(rng())).join(',')}]),`);
}
lines.push('];', 'const SUBSEEDS: &[(u32, &str, u32)] = &[');
for (const salt of ['', 'mesh', 'land', '海岸', 'A\u{1f30d}B']) {
  lines.push(`(42, ${JSON.stringify(salt)}, ${subSeed(42, salt)}),`);
}
lines.push('];', 'const KEYED: &[(u32, [i32; 3], u64)] = &[');
for (const [seed, a, b, c] of [[0,0,0,0], [42,7,-2,13], [4294967295,-2147483648,2147483647,-1]]) {
  lines.push(`(${seed}, [${a}, ${b}, ${c}], ${bits(keyed(seed,a,b,c))}),`);
}
lines.push('];', 'const ROUNDED: &[(u64, u64)] = &[');
for (const x of [0,-0,Math.PI,-Math.PI,1+2**-24,1e-300,Number.MIN_VALUE,1e289,1e290,Infinity,-Infinity]) {
  lines.push(`(${bits(x)}, ${bits(round24(x))}),`);
}
lines.push('];', 'type NoiseFixture = (u32, [f64; 3], [u64; 3]);', 'const NOISE: &[NoiseFixture] = &[');
// All six tetrahedron orders, ties, negative lattice positions and larger octaves.
for (const [seed,p] of [[42,[0,0,0]],[42,[0.3,0.2,0.1]],[42,[0.3,0.1,0.2]],[42,[0.2,0.1,0.3]],[42,[0.1,0.2,0.3]],[42,[0.1,0.3,0.2]],[42,[0.2,0.3,0.1]],[0,[-1.2,3.4,-5.6]],[4294967295,[256.1,-256.2,0.3]]]) {
  const n = noise3(seed);
  lines.push(`(${seed}, [${p.map(float).join(',')}], [${[n(...p),fbm3(n,4,0.6,2)(...p),ridged3(n,5,0.5)(...p)].map(bits).join(',')}]),`);
}
lines.push('];', `const TILE: &[u32] = &[${Array.from(tileableFbm(42,8,2,2,0.5),f32bits).join(',')}];`);
lines.push('const TRIG_CANARY: &[(u64, u32, u32)] = &[');
for (let i = 0; i < 256; i++) {
  const angle = (i / 256) * Math.PI * 2;
  lines.push(`(${bits(angle)}, ${f32bits(Math.cos(angle))}, ${f32bits(Math.sin(angle))}),`);
}
lines.push('];');
await writeFile(output, lines.join('\n')+'\n');
execFileSync('rustfmt', ['--edition', '2021', output]);
